# 42.列表案例3
# 生成1-20的平方列表
list_a = []
for i in range(1,21):
    list_a.append(i**2)
print(list_a)

# 方式二：列表推导式：列表名字 = [要输入的值 for i in 序列/列表]
num_list2 = [i**2 for i in range(1,21)]
print(num_list2)

